#include <iostream>
#include <clocale>

using namespace std;

// Рекурсивная функция для решения задачи Ханойской башни
// n - количество дисков, a - откуда, b - куда, c - вспомогательный стержень
void hanoi(int n, char a, char b, char c) {
    // Базовое условие выхода из рекурсии: если диск остался один
    if (n == 1) {
        cout << "Перенести диск 1 с стержня " << a << " на стержень " << b << endl;
        return; // Возврат из функции
    }

    // Шаг 1: переносим n-1 дисков со стержня a на вспомогательный стержень c
    hanoi(n - 1, a, c, b);

    // Шаг 2: переносим самый большой оставшийся диск со стержня a на целевой стержень b
    cout << "Перенести диск " << n << " с стержня " << a << " на стержень " << b << endl;

    // Шаг 3: переносим n-1 дисков со вспомогательного стержня c на целевой стержень b
    hanoi(n - 1, c, b, a);
}

int main() {

    setlocale(LC_ALL, ".UTF8");

    int count = 5; // Количество дисков (гаек) на стержне

    cout << "Решение головоломки Ханойская башня для " << count << " дисков:" << endl;
    cout << "Стержень А - исходный, С - вспомогательный, В - целевой." << endl << endl;

    // Запуск рекурсивной функции: перенос 5 дисков с 'A' на 'B' через 'C'
    hanoi(count, 'A', 'B', 'C');

    return 0;
}

