#include <iostream>  // Подключение библиотеки для ввода-вывода
#include <cstdlib>   // Подключение библиотеки для system()
using namespace std; // Использование стандартного пространства имен

// Лабораторная работа №4, вариант 24
// Однонаправленное кольцо на основе статического массива
// (просмотр слева направо, от последнего элемента можно перейти к первому).
//  1) Создать кольцо.
//  2) Распечатать кольцо, начиная с K-го элемента и до (K-1)-го.
//  3) Упорядочить элементы по возрастанию.
//  4) Удалить из кольца четные элементы.
//  5) Распечатать кольцо, начиная с K-го элемента и до (K-1)-го.

const int N = 100;   // Максимальная длина массива (псевдопеременные границы)

// Печать кольца: начиная с K-го элемента (нумерация с 1), всего n элементов,
// то есть до (K-1)-го элемента включительно; после последнего элемента идет первый
void printRing(const int a[], int n, int k) {
    if (n == 0) {                            // Если элементов не осталось
        cout << "Кольцо пусто" << endl;      // Сообщаем, что печатать нечего
        return;                              // Выход из функции
    }
    int start = (k - 1) % n;                 // Индекс стартового элемента (K приводится к кольцу)
    for (int j = 0; j < n; j++) {            // Обход ровно n элементов
        int i = (start + j) % n;             // Переход по кольцу: после a[n-1] снова a[0]
        cout << a[i] << " ";                 // Вывод текущего элемента
    }
    cout << endl;                            // Переход на новую строку
}

int main() {                                 // Главная функция
#ifdef _WIN32
    system("chcp 65001 > nul");              // Русский текст в консоли Windows
#endif
    int a[N];                                // Массив, в котором хранится кольцо
    int n;                                   // Реальная длина кольца (n <= N)
    int k;                                   // Номер элемента, с которого начинается печать

    cout << "Введите количество элементов (1.." << N << "): ";   // Приглашение к вводу n
    cin >> n;                                // Ввод реальной длины
    if (n < 1 || n > N) {                    // Проверка допустимости длины
        cout << "Недопустимая длина кольца" << endl;             // Сообщение об ошибке
        return 1;                            // Завершение с кодом ошибки
    }
    cout << "Введите " << n << " целых чисел: ";                 // Приглашение к вводу элементов
    for (int i = 0; i < n; i++)              // Цикл заполнения массива
        cin >> a[i];                         // Ввод i-го элемента
    cout << "Введите номер K начального элемента (1.." << n << "): "; // Приглашение к вводу K
    cin >> k;                                // Ввод K
    if (k < 1 || k > n) {                    // Проверка допустимости K
        cout << "Недопустимое значение K" << endl;               // Сообщение об ошибке
        return 1;                            // Завершение с кодом ошибки
    }

    cout << "\nИсходное кольцо, начиная с элемента K = " << k << ":" << endl;
    printRing(a, n, k);                      // Пункт 2: печать кольца с K-го элемента

    for (int i = 0; i < n - 1; i++)          // Пункт 3: сортировка методом пузырька по возрастанию
        for (int j = 0; j < n - 1 - i; j++)  // Внутренний проход по неупорядоченной части
            if (a[j] > a[j + 1]) {           // Если соседние элементы стоят в неверном порядке
                int tmp = a[j];              // Обмен значений через вспомогательную переменную
                a[j] = a[j + 1];
                a[j + 1] = tmp;
            }
    cout << "\nКольцо после упорядочивания по возрастанию, начиная с K = " << k << ":" << endl;
    printRing(a, n, k);                      // Печать упорядоченного кольца

    int m = 0;                               // Новая длина кольца после удаления четных
    for (int i = 0; i < n; i++)              // Пункт 4: удаление четных элементов
        if (a[i] % 2 != 0)                   // Нечетное число (для отрицательных % дает -1, тоже != 0)
            a[m++] = a[i];                   // Нечетный элемент переносим влево, длину m увеличиваем
    n = m;                                   // Реальная длина кольца уменьшилась

    cout << "\nКольцо после удаления четных элементов, начиная с K = " << k << ":" << endl;
    printRing(a, n, k);                      // Пункт 5: печать итогового кольца
    return 0;                                // Возвращение значения 0
}