#include <iostream>  // Подключение библиотеки для ввода-вывода
#include <iomanip>   // Подключение библиотеки для форматирования вывода (setw, setprecision)
#include <cmath>     // Подключение библиотеки для математических функций (log, fabs, pow)
#ifdef _WIN32
#include <windows.h> // Для переключения консоли Windows на кодировку UTF-8
#endif
using namespace std; // Использование стандартного пространства имен

// Лабораторная работа №3, вариант 24
// Функция: y = ln(1 / (2 + 2x + x^2)),  -2 <= x <= -0,1
// Разложение: S = -(1+x)^2 + (1+x)^4/2 - ... + (-1)^n * (1+x)^(2n) / n
// Общий член ряда: a_k = (-1)^k * t^k / k, где t = (1+x)^2

int main() {                                 // Главная функция
#ifdef _WIN32
    SetConsoleOutputCP(65001);               // Корректный вывод русского текста в консоли Windows
#endif
    const double A = -2.0;                   // Левая граница отрезка изменения x
    const double B = -0.1;                   // Правая граница отрезка изменения x
    const int K = 10;                        // Число участков разбиения отрезка [A; B]
    const int N = 40;                        // Заданное число слагаемых суммы (вариант 24)
    const double EPS = 0.0001;               // Заданная точность вычисления суммы
    const double H = (B - A) / K;            // Шаг изменения аргумента x

    cout << "Вычисление функции" << endl;    // Заголовок таблицы результатов
    cout << fixed << setprecision(6);        // Вывод вещественных чисел с 6 знаками после запятой

    for (int i = 0; i <= K; i++) {           // Внешний цикл: изменение параметра x
        double x = A + i * H;                // Текущее значение аргумента x
        double t = (1 + x) * (1 + x);        // Вспомогательная величина t = (1+x)^2

        // а) Арифметический цикл: сумма для заданного n
        double c = 1.0;                      // Множитель c_k = (-t)^k, начальное значение c_0 = 1
        double sn = 0.0;                     // Сумма SN для заданного n
        for (int k = 1; k <= N; k++) {       // Цикл по номеру слагаемого от 1 до n
            c = c * (-t);                    // Рекуррентный пересчет: c_k = c_(k-1) * (-t)
            sn = sn + c / k;                 // Добавление слагаемого a_k = c_k / k
        }

        // б) Итерационный цикл: сумма для заданной точности EPS
        c = 1.0;                             // Сброс множителя c_k
        double se = 0.0;                     // Сумма SE для заданной точности
        double a;                            // Текущее слагаемое ряда
        int k = 0;                           // Счетчик слагаемых
        do {                                 // Цикл с постусловием
            k++;                             // Переход к следующему номеру слагаемого
            c = c * (-t);                    // Рекуррентный пересчет множителя c_k
            a = c / k;                       // Вычисление текущего слагаемого a_k
            se = se + a;                     // Добавление слагаемого к сумме
        } while (fabs(a) >= EPS);            // Повторять, пока модуль слагаемого не станет меньше EPS

        double y = log(1.0 / (2 + 2 * x + x * x)); // Точное значение функции

        cout << "X=" << setw(9) << x             // Вывод x
            << "  SN=" << setw(10) << sn        // Вывод суммы для заданного n
            << "  SE=" << setw(10) << se        // Вывод суммы для заданной точности
            << "  Y=" << setw(10) << y          // Вывод точного значения функции
            << "  NE=" << k << endl;               // NE - число слагаемых, потребовавшееся для точности EPS
    }
    return 0;                                // Возвращение значения 0
}