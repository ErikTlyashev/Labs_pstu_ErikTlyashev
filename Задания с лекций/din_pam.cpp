#include <iostream>

using namespace std;

// Задание 3: память без delete до конца программы.
// Идея: ОС сама забирает всю память процесса при его завершении,
// поэтому "забытый" delete не оставит память занятой после выхода.
// Но: это утечка с точки зрения самой программы (пока она работает),
// деструкторы не вызываются, а санитайзеры/valgrind будут ругаться.
struct Noisy {
    ~Noisy() { cout << "Деструктор Noisy вызван\n"; }
};

int main() {
    int* big = new int[10'000'000];            // ~40 МБ, delete не вызываем
    for (int i = 0; i < 10'000'000; i += 1000) big[i] = i;
    cout << "Выделено ~40 МБ без delete\n";

    Noisy* obj = new Noisy;                    // delete нет -> деструктор НЕ сработает
    (void)obj;

    cout << "Конец программы: ОС освободит память, но "
        "сообщения от деструктора Noisy не будет.\n";
    return 0;
}