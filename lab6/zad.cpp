// Лабораторная работа №6, вариант 1
// Проверить, является ли строка палиндромом (читается одинаково слева направо
// и справа налево). Слова разделены пробелами, в конце текста стоит точка.
// При проверке пробелы и конечная точка не учитываются, регистр букв не различается.

const int MAXLEN = 256;  // Текст содержит не более 255 символов + завершающий нуль

// Ввод строки (замена устаревшей небезопасной функции gets)
void Gets(char s[]) {
    cin.getline(s, MAXLEN);                  // Чтение строки целиком вместе с пробелами
    if (cin.fail()) {                        // Если введено больше 255 символов
        cin.clear();                         // Сбрасываем состояние ошибки потока
        cin.ignore(10000, '\n');             // Отбрасываем остаток строки
    }
}

// Длина символа UTF-8 в байтах по его первому байту (русские буквы занимают 2 байта)
int symLen(unsigned char c) {
    if (c < 0x80) return 1;                  // Обычный символ ASCII
    if ((c >> 5) == 0x06) return 2;          // Двухбайтовый символ (кириллица)
    if ((c >> 4) == 0x0E) return 3;          // Трехбайтовый символ
    return 4;                                // Четырехбайтовый символ
}

// Код символа UTF-8, занимающего len байт, начиная с s[0]
unsigned symCode(const char s[], int len) {
    unsigned code = (unsigned char)s[0];     // Первый байт символа
    if (len > 1) code &= (0xFF >> (len + 1)); // Оставляем значащие биты первого байта
    for (int k = 1; k < len && s[k] != '\0'; k++)
        code = (code << 6) | ((unsigned char)s[k] & 0x3F); // Добавляем продолжающие байты
    return code;                             // Код символа
}

// Разбор строки на коды символов; возвращает число символов
int decode(const char s[], unsigned cp[]) {
    int i = 0, n = 0;                        // i - позиция в байтах, n - число символов
    while (s[i] != '\0') {                   // Пока строка не закончилась
        int len = symLen((unsigned char)s[i]); // Длина текущего символа в байтах
        cp[n++] = symCode(s + i, len);       // Запоминаем код символа
        i += len;                            // Переходим к следующему символу
    }
    return n;                                // Количество символов
}

// Приведение буквы к нижнему регистру (латиница и кириллица)
unsigned lower(unsigned c) {
    if (c >= 'A' && c <= 'Z') return c + 32;        // Латинские A-Z
    if (c >= 0x0410 && c <= 0x042F) return c + 32;  // Русские А-Я
    if (c == 0x0401) return 0x0451;                 // Буква Ё
    return c;                                       // Остальные символы не меняются
}

// Очистка строки: отбрасываются пробелы и конечная точка, буквы приводятся к нижнему регистру;
// результат записывается в t, возвращается его длина
int clean(const unsigned cp[], int n, unsigned t[]) {
    while (n > 0 && cp[n - 1] == ' ') n--;   // Отбрасываем пробелы в конце
    if (n > 0 && cp[n - 1] == '.') n--;      // Отбрасываем конечную точку
    int m = 0;                               // Длина очищенной строки
    for (int i = 0; i < n; i++)              // Копируем символы, кроме пробелов
        if (cp[i] != ' ')
            t[m++] = lower(cp[i]);           // Регистр не различается
    return m;                                // Длина очищенной строки
}

// Проверка: является ли строка палиндромом (результат: 1 - да, 0 - нет, -1 - нет символов)
int isPalindrome(const char s[]) {
    unsigned cp[MAXLEN];                     // Коды символов строки
    unsigned t[MAXLEN];                      // Символы без пробелов и конечной точки
    int n = decode(s, cp);                   // Разбор строки на символы
    int m = clean(cp, n, t);                 // Очистка строки
    if (m == 0) return -1;                   // В строке нет символов для проверки
    for (int i = 0, j = m - 1; i < j; i++, j--) // Сравниваем символы с концов к середине
        if (t[i] != t[j])
            return 0;                        // Нашли несовпадение - не палиндром
    return 1;                                // Все пары совпали - палиндром
}

