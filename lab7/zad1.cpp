#include <iostream>  // Подключение библиотеки для ввода-вывода
#include <cstring>   // Подключение библиотеки для работы со строками (strlen)
#include <cstdlib>   // Подключение библиотеки для system()
using namespace std; // Использование стандартного пространства имен

// Лабораторная работа №7.1, вариант 24. Перегрузка функций.
// а) для массива целых чисел удаляет все четные элементы;
// б) для строки удаляет все четные слова (слова с четными порядковыми номерами: 2-е, 4-е, ...).
// Обе функции называются removeEven и различаются типами параметров.

// а) Удаляет четные элементы массива, возвращает новую длину массива
int removeEven(int a[], int n) {
    int m = 0;                               // Новая длина массива
    for (int i = 0; i < n; i++)              // Просмотр всех элементов
        if (a[i] % 2 != 0)                   // Нечетный элемент оставляем (для отрицательных % дает -1)
            a[m++] = a[i];                   // Переносим элемент влево, увеличиваем длину
    return m;                                // Новая длина
}

// б) Удаляет из строки слова с четными порядковыми номерами; слова разделены пробелами
void removeEven(char s[]) {
    int len = strlen(s);                     // Длина исходной строки
    int out = 0;                             // Позиция записи результата
    int num = 0;                             // Порядковый номер текущего слова
    int i = 0;                               // Позиция чтения
    while (i < len) {                        // Просмотр строки
        while (i < len && s[i] == ' ') i++;  // Пропуск пробелов между словами
        if (i >= len) break;                 // Строка закончилась
        int start = i;                       // Начало слова
        while (i < len && s[i] != ' ') i++;  // Поиск конца слова
        num++;                               // Номер слова
        if (num % 2 != 0) {                  // Нечетное по номеру слово остается
            if (out > 0) s[out++] = ' ';     // Между словами ставится один пробел
            for (int j = start; j < i; j++)  // Копирование слова
                s[out++] = s[j];
        }
    }
    s[out] = '\0';                           // Завершающий нуль-символ
}

int main() {                                 // Главная функция
#ifdef _WIN32
    system("chcp 65001 > nul");              // Русский текст в консоли Windows
#endif
    // а) массив целых чисел
    int a[100];                              // Массив
    int n;                                   // Длина массива
    cout << "а) Введите количество элементов (1..100): ";
    cin >> n;                                // Ввод длины
    if (n < 1 || n > 100) { cout << "Недопустимая длина" << endl; return 1; }
    cout << "Введите целые числа (" << n << " шт.): ";
    for (int i = 0; i < n; i++) cin >> a[i]; // Ввод элементов
    n = removeEven(a, n);                    // Вызов версии для массива
    cout << "Массив без четных элементов:";
    if (n == 0) cout << " (пусто)";          // Если ничего не осталось
    for (int i = 0; i < n; i++) cout << " " << a[i];
    cout << endl;

    // б) строка
    char s[256];                             // Строка
    cin.ignore(1000, '\n');                  // Пропуск конца предыдущей строки ввода
    cout << "б) Введите строку (слова через пробел): ";
    cin.getline(s, 256);                     // Ввод строки целиком
    removeEven(s);                           // Вызов версии для строки
    cout << "Строка без четных слов: " << s << endl;
    return 0;                                // Возвращение значения 0
}
