#include <iostream>  
#include <cmath>     // подключаем математическую библиотеку (exp, sqrt)
using namespace std; 

int main() {                      
    double sum = 0.0;             // переменная для накопления суммы, изначально равна 0
    int n = 9;                    // количество членов ряда (по заданию — 9)

    cout << "Вычисление суммы 9 членов ряда a_n = e^(-sqrt(n))" << endl; 
    

    for (int i = 1; i <= n; i++) {          // цикл: i меняется от 1 до 9 (9 итераций)
        double a_n = exp(-sqrt(i));          // вычисляем i-й член ряда: e в степени (-корень из i)
        sum += a_n;                          // добавляем вычисленный член к общей сумме
        cout << "a_" << i << " = " << a_n << endl; // выводим номер члена и его значение
    }                                        

    
    cout << "Сумма 9 членов ряда = " << sum << endl; // выводим итоговую сумму

    return 0;                       
}                                    
