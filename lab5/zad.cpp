#include <iostream>  // Подключение библиотеки для ввода-вывода
#include <iomanip>   // Подключение библиотеки для форматирования вывода (setw)
#include <cstdlib>   // Подключение библиотеки для system()
using namespace std; // Использование стандартного пространства имен

// Лабораторная работа №5, вариант 24
// Определить, сколько элементов двумерного массива больше любого элемента
// на главной диагонали (то есть больше максимального элемента главной диагонали).
// Массив передается в функции как параметр.

const int MAXN = 20; // Максимальное число строк
const int MAXM = 20; // Максимальное число столбцов

// Ввод элементов матрицы n x m с клавиатуры
void inputMatrix(int a[][MAXM], int n, int m) {
    for (int i = 0; i < n; i++)              // Цикл по строкам
        for (int j = 0; j < m; j++)          // Цикл по столбцам
            cin >> a[i][j];                  // Ввод элемента a[i][j]
}

// Печать матрицы n x m
void printMatrix(const int a[][MAXM], int n, int m) {
    for (int i = 0; i < n; i++) {            // Цикл по строкам
        for (int j = 0; j < m; j++)          // Цикл по столбцам
            cout << setw(5) << a[i][j];      // Вывод элемента в поле шириной 5
        cout << endl;                        // Переход на новую строку
    }
}

// Максимальный элемент главной диагонали (элементы a[i][i], i < min(n, m))
int maxDiagonal(const int a[][MAXM], int n, int m) {
    int d = (n < m) ? n : m;                 // Длина главной диагонали
    int mx = a[0][0];                        // Начальное значение максимума
    for (int i = 1; i < d; i++)              // Просмотр остальных элементов диагонали
        if (a[i][i] > mx)                    // Если найден больший элемент
            mx = a[i][i];                    // Запоминаем его
    return mx;                               // Возвращаем максимум
}

// Количество элементов, которые больше любого элемента главной диагонали
int countGreater(const int a[][MAXM], int n, int m) {
    int mx = maxDiagonal(a, n, m);           // Больше любого элемента диагонали = больше ее максимума
    int cnt = 0;                             // Счетчик элементов
    for (int i = 0; i < n; i++)              // Цикл по строкам
        for (int j = 0; j < m; j++)          // Цикл по столбцам
            if (a[i][j] > mx)                // Сравнение элемента с максимумом диагонали
                cnt++;                       // Увеличиваем счетчик
    return cnt;                              // Возвращаем результат
}

int main() {                                 // Главная функция
#ifdef _WIN32
    system("chcp 65001 > nul");              // Русский текст в консоли Windows
#endif
    int a[MAXN][MAXM];                       // Двумерный массив
    int n, m;                                // Реальные размеры массива

    cout << "Введите число строк и столбцов (1.." << MAXN << "): "; // Приглашение к вводу
    cin >> n >> m;                           // Ввод размеров
    if (n < 1 || n > MAXN || m < 1 || m > MAXM) { // Проверка допустимости размеров
        cout << "Недопустимые размеры массива" << endl;  // Сообщение об ошибке
        return 1;                            // Завершение с кодом ошибки
    }
    cout << "Введите элементы массива (" << n << " x " << m << "):" << endl;
    inputMatrix(a, n, m);                    // Ввод матрицы (массив передается как параметр)

    cout << "\nИсходный массив:" << endl;
    printMatrix(a, n, m);                    // Печать матрицы

    cout << "\nМаксимальный элемент главной диагонали: " << maxDiagonal(a, n, m) << endl;
    cout << "Количество элементов, больших любого элемента главной диагонали: "
        << countGreater(a, n, m) << endl;   // Вывод результата
    return 0;                                // Возвращение значения 0
}
